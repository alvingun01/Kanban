<#
.SYNOPSIS
  Install the `kanban` command for the current user.

.DESCRIPTION
  Writes a small shim to %LOCALAPPDATA%\kanban\bin and puts that directory on
  your user PATH. The shim points at this folder, so the tool is never copied:
  a fix here reaches every project at once. Re-run after moving this folder.

  Nothing is installed system-wide and no admin rights are needed.

  The window is held open at the end so you can read the result. Windows'
  "Run with PowerShell" closes the window the instant a script finishes, which
  makes success and failure look identical. Pass -NoPause in scripts.

.EXAMPLE
  .\install.ps1
.EXAMPLE
  .\install.ps1 -Uninstall
#>

[CmdletBinding()]
param(
    [switch]$Uninstall,
    [switch]$NoPause
)

$ErrorActionPreference = "Stop"

$toolRoot = $PSScriptRoot
$binDir   = Join-Path $env:LOCALAPPDATA "kanban\bin"
$shimCmd  = Join-Path $binDir "kanban.cmd"
$shimPs1  = Join-Path $binDir "kanban.ps1"


function Wait-BeforeClosing {
    if ($NoPause) { return }
    if (-not [Environment]::UserInteractive) { return }
    try {
        Write-Host ""
        Write-Host "Press Enter to close this window..." -ForegroundColor DarkGray
        [void](Read-Host)
    } catch {
        # stdin redirected: nothing to wait for.
    }
}

function Get-UserPath {
    $value = [Environment]::GetEnvironmentVariable("Path", "User")
    if ($null -eq $value) { return "" }
    return $value
}

function Find-Python {
    foreach ($candidate in @("python", "python3", "py")) {
        $found = Get-Command $candidate -ErrorAction SilentlyContinue
        if (-not $found) { continue }

        $prev = $ErrorActionPreference
        $ErrorActionPreference = "Continue"
        $version = & $found.Source -c "import sys; print('%d.%d' % sys.version_info[:2])" 2>$null
        $rc = $LASTEXITCODE
        $ErrorActionPreference = $prev

        if ($rc -ne 0 -or -not $version) { continue }
        $parts = $version.Trim() -split '\.'
        if ([int]$parts[0] -ge 3 -and [int]$parts[1] -ge 8) { return $found.Source }
    }
    throw @"
Python 3.8 or newer is required, and I could not find it.

Install it from https://www.python.org/downloads/ and make sure you tick
"Add python.exe to PATH" on the first screen of the installer.

Then close this window, open a new one, and run this script again.
"@
}

function Test-Package {
    param([string]$Python)

    # Run from a neutral directory. Python puts the current directory on its
    # own search path for -m, so testing from the tool folder would pass even
    # if PYTHONPATH were wrong -- the check would prove the wrong thing.
    $probe = Join-Path ([System.IO.Path]::GetTempPath()) ("kanban-probe-" + [guid]::NewGuid().ToString("N"))
    New-Item -ItemType Directory -Force -Path $probe | Out-Null
    $ok = $false
    $clue = ""
    try {
        $env:PYTHONPATH = $toolRoot
        # Start-Process with redirect files, rather than `&` with `2>&1`:
        # PowerShell 5.1 wraps a native command's stderr in ErrorRecords, which
        # $ErrorActionPreference="Stop" turns into a terminating error. This
        # also keeps Python's traceback off the screen -- it is alarming and
        # unhelpful to someone just trying to install the thing.
        $outFile = Join-Path $probe "out.txt"
        $errFile = Join-Path $probe "err.txt"
        $proc = Start-Process -FilePath $Python `
            -ArgumentList @("-m", "kanban", "--help") `
            -WorkingDirectory $probe -NoNewWindow -Wait -PassThru `
            -RedirectStandardOutput $outFile -RedirectStandardError $errFile
        $ok = ($proc.ExitCode -eq 0)
        if (-not $ok -and (Test-Path $errFile)) {
            # Keep the last line: that is where Python puts the actual reason.
            $lines = @(Get-Content $errFile | Where-Object { $_.Trim() })
            if ($lines.Count) { $clue = $lines[-1].Trim() }
        }
    } finally {
        try { Remove-Item -Recurse -Force $probe -ErrorAction Stop } catch {}
    }
    if (-not $ok) {
        $message = @"
The kanban files in this folder do not run, so nothing was installed:

  $toolRoot

The folder may be incomplete or damaged. Try downloading or copying it again.
"@
        if ($clue) { $message += "`nTechnical detail: $clue" }
        throw $message
    }
}

function Invoke-Install {
    $python = Find-Python
    Test-Package -Python $python

    New-Item -ItemType Directory -Force -Path $binDir | Out-Null

    $cmdBody = @"
@echo off
REM Shim generated by install.ps1. All logic lives in the package below, so
REM this file only changes if the tool moves. Re-run install.ps1 if it does.
setlocal
set "PYTHONPATH=$toolRoot"
"$python" -m kanban %*
"@
    Set-Content -Path $shimCmd -Value $cmdBody -Encoding ascii

    $ps1Body = @"
# Shim generated by install.ps1.
`$env:PYTHONPATH = "$toolRoot"
& "$python" -m kanban @args
"@
    Set-Content -Path $shimPs1 -Value $ps1Body -Encoding utf8

    $userPath = Get-UserPath
    $alreadyOnPath = ($userPath -split ';') -contains $binDir
    if (-not $alreadyOnPath) {
        $joined = if ($userPath) { "$userPath;$binDir" } else { $binDir }
        [Environment]::SetEnvironmentVariable("Path", $joined, "User")
        $pathNote = "Added to your PATH so you can type `kanban` anywhere."
    } else {
        $pathNote = "Already on your PATH."
    }
    $env:Path = "$env:Path;$binDir"

    Write-Host ""
    Write-Host "  kanban is installed." -ForegroundColor Green
    Write-Host ""
    Write-Host "  tool     $toolRoot"
    Write-Host "  command  $shimCmd"
    Write-Host "  python   $python"
    Write-Host "  path     $pathNote"
    Write-Host ""
    Write-Host "  ---------------------------------------------------------"
    Write-Host "  WHAT TO DO NEXT" -ForegroundColor Cyan
    Write-Host ""
    Write-Host "  1. Close this window."
    Write-Host "  2. Open a NEW PowerShell window (Start > type powershell)."
    Write-Host "     A window opened before now will not know the command yet."
    Write-Host "  3. Go to a project folder and set up a board:"
    Write-Host ""
    Write-Host "        cd C:\some\project"
    Write-Host "        kanban init"
    Write-Host ""
    Write-Host "  4. Then double-click Dashboard.cmd in that folder."
    Write-Host "     Everything happens in the page that opens."
    Write-Host "  ---------------------------------------------------------"
}

function Invoke-Uninstall {
    if (Test-Path $binDir) { Remove-Item -Recurse -Force $binDir }
    $entries = (Get-UserPath) -split ';' | Where-Object { $_ -and $_ -ne $binDir }
    [Environment]::SetEnvironmentVariable("Path", ($entries -join ';'), "User")
    Write-Host ""
    Write-Host "  Removed the kanban command and its PATH entry." -ForegroundColor Green
    Write-Host "  Your boards and cards were not touched -- they live in your"
    Write-Host "  project folders, not with the tool."
}

$exitCode = 0
try {
    if ($Uninstall) { Invoke-Uninstall } else { Invoke-Install }
} catch {
    Write-Host ""
    Write-Host "  Nothing was installed." -ForegroundColor Red
    Write-Host ""
    foreach ($line in ($_.Exception.Message -split "`n")) {
        Write-Host ("  " + $line.TrimEnd())
    }
    Write-Host ""
    Write-Host "  If you want help, copy the text above." -ForegroundColor DarkGray
    $exitCode = 1
}

Wait-BeforeClosing
exit $exitCode
